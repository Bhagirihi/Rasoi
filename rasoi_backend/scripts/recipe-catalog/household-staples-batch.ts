import type { RecipeCatalogEntry } from './types';

function kw(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

type StapleInput = {
  num: number;
  kitchenStyleId: string;
  region: string;
  title: string;
  prepTime: number;
  calories: number;
  difficulty: 'Easy' | 'Medium' | 'Hard';
  description: string;
  tags: string[];
  ingredients: Array<{ name: string; isStaple: boolean }>;
  steps: string[];
  kitchenStyleIds?: string[];
  dietType?: 'Veg' | 'Egg' | 'Non-Veg';
};

function staple(input: StapleInput): RecipeCatalogEntry {
  return {
    id: `household-${String(input.num).padStart(2, '0')}`,
    kitchenStyleId: input.kitchenStyleId,
    kitchenStyleIds: input.kitchenStyleIds ?? [input.kitchenStyleId],
    title: input.title,
    prepTime: input.prepTime,
    calories: input.calories,
    region: input.region,
    dietType: input.dietType ?? 'Veg',
    difficulty: input.difficulty,
    description: input.description,
    imageKeyword: kw(input.title),
    tags: input.tags,
    ingredients: input.ingredients,
    steps: input.steps,
  };
}

